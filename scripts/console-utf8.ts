// Windows-консоль по умолчанию использует кодовую страницу 866/1251, поэтому
// UTF-8 вывод Node превращается в «кракозябры». Переключаем консоль на UTF-8,
// чтобы русские сообщения скриптов читались.
//
// Импортировать первым, до модулей, которые что-то печатают.

import { execSync } from "node:child_process";

if (process.platform === "win32") {
  try {
    execSync("chcp 65001", { stdio: "ignore" });
  } catch {
    // Не критично — скрипт продолжит работу, просто текст может быть нечитаемым.
  }
}
